    fun forDate(date: LocalDate = LocalDate.now()): Day {
        val key = "%04d-%02d-%02d".format(date.year, date.monthValue, date.dayOfMonth)
        val doy = date.dayOfYear
        val year = date.year
        val season = when (date.monthValue) {
            12, 1, 2 -> "зима"
            3, 4, 5 -> "весна"
            6, 7, 8 -> "лето"
            else -> "осень"
        }
        val theme = yearThemes[Math.floorMod(year - 2026, yearThemes.size)]
        val fact = facts[(doy + year * 3) % facts.size]
        val tip = tips[(doy + year * 7) % tips.size]
        val curiosity = curiosities[(doy + year * 11) % curiosities.size]
        return Day(
            date = date,
            dateText = "${date.dayOfMonth} ${months[date.monthValue - 1]}",
            weekday = weekdays[date.dayOfWeek.value - 1],
            season = season,
            fact = "Полезно знать: ${fact.trimEnd('.')}.",
            tip = tip,
            curiosity = curiosity,
            weekdayTip = weekdayTips[date.dayOfWeek.value - 1],
            yearTheme = theme.first,
            yearThemeHint = theme.second,
            key = key,
        )
    }

