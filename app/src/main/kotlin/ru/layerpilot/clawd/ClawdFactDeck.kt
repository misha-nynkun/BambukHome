/**
 * Локальная колода знаний Clawd.
 *
 * Факт и практический совет комбинируются в уникальную карточку. Перебор идёт
 * по перестановке, а не случайным выбором: одна и та же карточка не повторится,
 * пока не будут показаны все сочетания. При ~170 000 сочетаний и 5 нажатиях в
 * день этого хватает почти на 90 лет без сети и без ИИ.
 */
object ClawdFactDeck {
    private val facts: List<String> by lazy {
        (deepFacts + ClawdDaily.allFacts() + ClawdDaily.allCuriosities())
            .map { it.trim().trimEnd('.') }
            .filter { it.length >= 12 && !it.startsWith("Clawd ", true) }
            .distinct()
    }

    private val tips: List<String> by lazy {
        ClawdDaily.allTips()
            .map { it.trim().trimEnd('.') }
            .filter { it.length >= 8 }
            .distinct()
    }

    fun combinations(): Long = facts.size.toLong() * tips.size.toLong()

    fun summary(): String {
        val total = combinations()
        val years = (total / 5L / 365L).coerceAtLeast(1L)
        val pretty = "%,d".format(total).replace(',', ' ')
        return "Более $pretty карточек — при 5 нажатиях в день это примерно $years лет без повторов"
    }

    fun next(memory: ClawdMemoryStore): String {
        if (facts.isEmpty() || tips.isEmpty()) {
            return "Факт: первый слой решает судьбу всей печати.\n\nСовет: проверь его глазами."
        }
        val total = facts.size.toLong() * tips.size.toLong()
        val counter = memory.nextFactCounter()
        val step = stepFor(total)
        val index = (counter % total) * step % total
        val fact = facts[(index / tips.size).toInt()]
        val tip = tips[(index % tips.size).toInt()]
        return "Факт: $fact\n\nСовет: ${tip.replaceFirstChar { c ->
            if (c.isLowerCase()) c.titlecase() else c.toString()
        }}"
    }

    /** Шаг, взаимно простой с размером колоды: так перестановка не зацикливается раньше. */
    private fun stepFor(total: Long): Long {
        var candidate = 104_729L
        while (gcd(candidate, total) != 1L) candidate += 2L
        return candidate
    }

    private fun gcd(a: Long, b: Long): Long {
        var x = a
        var y = b
        while (y != 0L) {
            val t = x % y
            x = y
            y = t
        }
        return x
    }

