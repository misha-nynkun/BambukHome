    val entries: List<HmsExplanation> get() = exact

    fun explain(code: String): HmsExplanation {
        exact.firstOrNull { it.code.equals(code, true) }?.let { return it }
        val family = families.firstOrNull { code.startsWith(it.first, true) }
        return if (family != null) {
            HmsExplanation(
                code,
                family.second,
                "Код относится к модулю «${family.second}». Точное описание зависит от модели и прошивки.",
                listOf(family.third, "Откройте экран принтера и проверьте текущую ошибку.",
                    "Если ошибка повторяется — запишите код в журнал обслуживания."),
            )
        } else {
            HmsExplanation(
                code, "Неизвестный код HMS",
                "Приложение пока не знает точное описание этого кода.",
                listOf("Проверьте экран принтера.", "Перезапустите принтер.",
                    "Запишите код в журнал и проверьте после обновления прошивки."),
                severity = "info",
            )
        }
    }

    fun search(query: String): List<HmsExplanation> {
        val q = query.trim().lowercase()
        if (q.isBlank()) return exact
        return exact.filter {
            it.code.lowercase().contains(q) || it.title.lowercase().contains(q) ||
                it.cause.lowercase().contains(q)
        }
    }
